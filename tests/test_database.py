"""Checks for the shared database layer; no real PostgreSQL server is needed here."""
import sys  # Let pytest find the application from the tests folder.
from pathlib import Path  # Find the project directory.
from types import SimpleNamespace  # Build a small fake driver for connection tests.
import pytest  # Run assertions and temporary-file tests.
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import database  # Test the same database module the agents use.


def test_row_supports_names_indexes_and_unpacking():
    row=database.DatabaseRow(['name','quantity'],['General',3])
    assert row[0]=='General' and row['quantity']==3
    assert dict(row)=={'name':'General','quantity':3}
    assert tuple(row)==('General',3)


def test_placeholders_leave_quoted_question_marks_alone():
    assert database.postgres_parameters("SELECT '?' AS question, ? AS value") == "SELECT '?' AS question, %s AS value"


def test_percent_literals_are_not_treated_as_parameters():
    assert database.postgres_parameters("SELECT '%s', '100%', ?") == "SELECT '%%s', '100%%', %s"


def test_only_generated_primary_keys_become_identity_columns():
    sql=database.POSTGRES_SCHEMA
    assert 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in sql
    assert 'booking_id INTEGER PRIMARY KEY REFERENCES bookings(id)' in sql
    assert 'ticket_id INTEGER PRIMARY KEY REFERENCES tickets(id)' in sql
    assert 'sequence INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in sql


def test_explicit_sqlite_path_wins_over_database_url(tmp_path,monkeypatch):
    monkeypatch.setenv('DATABASE_URL','postgresql://unused.invalid/example')
    with database.transaction(tmp_path/'local.db') as db:
        db.execute('CREATE TABLE example(value INTEGER)')
        db.execute('INSERT INTO example VALUES (?)',(7,))
    with database.connect(tmp_path/'local.db') as db:
        assert db.execute('SELECT value FROM example').fetchone()[0]==7


def test_postgres_wrapper_binds_values_and_uses_transaction_lock(monkeypatch):
    calls=[]
    class Driver:
        def execute(self,sql,values=None):
            calls.append((sql,values))
        def commit(self): calls.append(('commit',None))
        def rollback(self): calls.append(('rollback',None))
        def close(self): calls.append(('close',None))
    monkeypatch.setattr(database,'psycopg',SimpleNamespace(connect=lambda *a,**k: Driver()))
    db=database.PostgresConnection('postgresql://test.invalid/example')
    database.begin_write(db)
    db.execute('UPDATE venues SET open_for_hire=? WHERE id=?',(True,9))
    db.commit();db.close()
    assert ('SELECT pg_advisory_xact_lock(%s)',(database.WRITE_LOCK,)) in calls
    assert ('UPDATE venues SET open_for_hire=%s WHERE id=%s',(1,9)) in calls


def test_postgres_insert_asks_for_generated_id():
    calls=[]
    class Driver:
        dialect='postgresql'
        def execute(self,sql,values):
            calls.append(sql)
            return SimpleNamespace(fetchone=lambda: (42,))
    assert database.insert_id(Driver(),'INSERT INTO venues(name) VALUES (?)',('Hall',))==42
    assert calls==['INSERT INTO venues(name) VALUES (?) RETURNING id']


def test_transaction_rolls_back_partial_changes(tmp_path):
    path=tmp_path/'rollback.db'
    with database.transaction(path) as db:
        db.execute('CREATE TABLE example(value INTEGER)')
    with pytest.raises(RuntimeError):
        with database.transaction(path) as db:
            db.execute('INSERT INTO example VALUES (1)')
            raise RuntimeError('Pretend a later agent failed')
    with database.connect(path) as db:
        assert db.execute('SELECT COUNT(*) FROM example').fetchone()[0]==0


def test_postgres_row_factory_handles_statements_without_rows():
    factory=database.postgres_row(SimpleNamespace(description=None))
    assert factory([]).keys()==[]
